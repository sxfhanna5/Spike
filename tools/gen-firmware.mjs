// Generates firmware/spike_egg/effects.h from src/egg/effects.json, so the simulator and the
// hardware play exactly the same light effects.   Run:  node tools/gen-firmware.mjs
import fs from 'node:fs'

const json = JSON.parse(fs.readFileSync(new URL('../src/egg/effects.json', import.meta.url), 'utf8'))
const KIND = { breathe: 'K_BREATHE', pulse: 'K_PULSE', fade: 'K_FADE', heatGain: 'K_HEATGAIN', seq: 'K_SEQ', sparkle: 'K_SPARKLE', hold: 'K_HOLD' }
const TARGET = { all: 'T_ALL', lit: 'T_LIT', new: 'T_NEW', unlit: 'T_UNLIT' }
const col = (c) => (c === '$module' ? 'COL_MODULE' : c === 'heat' ? 'COL_HEAT' : '0x' + c.replace('#', '').toUpperCase())
const f = (n) => (Number.isInteger(n) ? n.toFixed(1) : String(n)) + 'f'

const layer = (L) => {
  const o = { kind: KIND[L.kind], target: TARGET[L.target ?? 'all'], color: col(L.color ?? '#000000'), start: L.start ?? 0, dur: L.dur ?? 0, len: 0, step: 0, life: 0, fadeIn: L.fadeIn ?? 0, a: 0, b: 0, times: L.times ?? [], peaks: L.peaks ?? [], pal: (L.palette ?? []).map(col) }
  switch (L.kind) {
    case 'breathe': o.len = L.period; o.a = L.min; o.b = L.max; break
    case 'pulse': o.len = L.len; o.a = L.peak; break
    case 'fade': o.a = L.from; o.b = L.to; break
    case 'heatGain': o.a = L.from; o.b = L.to; break
    case 'seq': o.step = L.step; o.len = L.fade; break
    case 'sparkle': o.life = L.life; o.a = L.peak; o.b = L.rate; break
    case 'hold': o.a = L.level; break
  }
  const arr = (xs, fmt) => (xs.length ? xs.map(fmt).join(', ') : '0')
  return `    { ${o.kind}, ${o.target}, ${o.color}, ${o.start}, ${o.dur}, ${o.len}, ${o.step}, ${o.life}, ${o.fadeIn}, ${f(o.a)}, ${f(o.b)}, ${o.times.length}, { ${arr(o.times, String)} }, { ${arr(o.peaks, f)} }, ${o.pal.length}, { ${arr(o.pal, String)} } }`
}

const names = Object.keys(json.effects)
let out = `// AUTO-GENERATED by tools/gen-firmware.mjs from src/egg/effects.json. Do not edit by hand.
#pragma once
#include <stdint.h>

#define LED_COUNT ${json.limits.leds}
#define MAX_BRIGHTNESS ${json.limits.maxBrightness}   // of 255
#define COL_MODULE 0xFF000001UL    // colour sent by the app with C:
#define COL_HEAT   0xFF000002UL    // warm colour of each heat LED

enum Kind : uint8_t { K_BREATHE, K_PULSE, K_FADE, K_HEATGAIN, K_SEQ, K_SPARKLE, K_HOLD };
enum Target : uint8_t { T_ALL, T_LIT, T_NEW, T_UNLIT };

struct Layer {
  uint8_t kind, target;
  uint32_t color;
  uint16_t start, dur, len, step, life, fadeIn;
  float a, b;                // breathe min,max · pulse peak · fade from,to · hold level · sparkle peak,rate
  uint8_t nTimes; uint16_t times[8]; float peaks[8];
  uint8_t nPal; uint32_t pal[6];
};
struct Effect {
  const char* name;
  uint16_t dur;
  bool loop, replaceBase, holdAfter;
  uint8_t nLayers;
  Layer layers[8];
};

`
out += names.map((n, i) => `#define FX_${n} ${i}`).join('\n') + `\n#define FX_NONE 255\n#define FX_COUNT ${names.length}\n\n`
out += 'static const Effect EFFECTS[FX_COUNT] = {\n'
out += names
  .map((n) => {
    const e = json.effects[n]
    return `  { "${n}", ${e.dur}, ${!!e.loop}, ${!!e.replaceBase}, ${!!e.holdAfter}, ${e.layers.length}, {\n${e.layers.map(layer).join(',\n')}\n  } }`
  })
  .join(',\n')
out += '\n};\n'
fs.writeFileSync(new URL('../firmware/spike_egg/effects.h', import.meta.url), out)
console.log('firmware/spike_egg/effects.h written (' + names.length + ' effects)')
